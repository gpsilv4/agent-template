/**
 * Os casos da PROSA contra a ATRIBUICAO do `test-commit-msg.mjs`: o "built with"/"generated with" que e prosa de produto
 * passa, o que atribui a uma ferramenta reprova, e as linhas patologicas nao penduram (#289) — {{PROJECT_NAME}}
 *
 * Sairam do `test-commit-msg.mjs` quando ele chegou as 498 linhas (o Guard 17, #400). NAO e uma suite nem um modulo
 * descoberto: a suite importa-o e chama `casosDaProsa(test)` NO SITIO de onde o bloco saiu, com o `test` dela (os
 * contadores e o hook corrido sao dela). Sem sitios de recusa: so regista casos.
 */

/** @param {Function} test  o `test` do `test-commit-msg.mjs` */
export function casosDaProsa(test) {
  // #289: "built with X" casava em qualquer sitio da linha e com X em qualquer sitio do resto —
  // a paginacao por cursor e prosa, nao uma atribuicao. Recusar prosa ensina o `--no-verify`.
  test("subject `built with cursor pagination` passa", "feat(api): built with cursor pagination\n", { code: 0 });
  test("corpo `Built with cursor pagination ...` passa",
    "feat: x\n\nBuilt with cursor pagination for large lists.\n", { code: 0 });
  test("`Created with gemini style prompts` passa (o nome em minusculas e prosa)",
    "feat: x\n\nCreated with gemini style prompts in mind.\n", { code: 0 });
  test("`cursor-based pagination` passa (o sufixo hifenizado nao e atribuicao)",
    "feat: x\n\nBuilt with cursor-based pagination.\n", { code: 0 });

  // A prosa de um projeto que INTEGRA um modelo: a API/SDK nas palavras seguintes diz que se
  // construiu COM o modelo, e nao que ele escreveu o codigo (segunda passagem de leituras do #289).
  for (const msg of [
    "feat: x\n\nBuilt with Gemini API and response caching.\n",
    "feat: built with Claude and OpenAI APIs\n",
    "feat: x\n\nBuilt with the Claude Agent SDK\n",
    "feat: x\n\nBuilt with OpenAI's Responses API\n",
  ]) {
    test(`prosa de produto \`${msg.trim().split("\n").pop()}\` passa`, msg, { code: 0 });
  }

  // RECUSAS ASSUMIDAS, como a do Devin: o nome com MAIUSCULA, no fim da frase, ou seguido de um
  // conector (`cursor and ...`, que tem a forma de `copilot and reviewed by me`) e indistinguivel de
  // uma atribuicao (`This PR was generated with Claude Code` tem a mesma forma que `replies generated
  // by Gemini`). Deixar passar estas abria a porta a atribuicoes reais; a mensagem de recusa manda
  // reformular a frase. Ficam escritas para que a escolha seja explicita.
  for (const msg of [
    "docs: notes made by Copilot users in the survey\n",
    "feat(chat): replies generated by Gemini\n",
    "fix: x\n\nCaptions are generated by Gemini.\n",
    "feat: x\n\nBuilt with cursor and offset pagination\n",
    // So `built` faz de um modelo um PRODUTO construido com a API; `generated with ... API` nao.
    "feat(chat): replies generated with the Gemini API\n",
    // `Gemini-style`: o sufixo hifenizado de um nome com maiuscula.
    "feat: x\n\nCreated with Gemini-style prompts\n",
  ]) {
    test(`recusa assumida \`${msg.trim().split("\n").pop()}\``, msg, { code: 1 });
  }

  // Os nomes colados nos trailers continuam a reprovar, sem voltar a casar dentro de `Claudete`.
  for (const valor of ["ClaudeCode", "CursorAI", "GeminiCLI", "CopilotChat", "claude_code", "TabnineBot", "copilotbot", "Claude4 <bot@x.com>", "ClaudeSonnet4 <bot@x.com>", "GeminiPro <bot@x.com>", "CursorAgent <bot@x.com>"]) {
    test(`trailer com o nome colado \`${valor}\` reprova`, `fix: x\n\nCo-Authored-By: ${valor}\n`, { code: 1 });
  }

  // Sem backtracking catastrofico: o CI corre o hook sobre as mensagens de um PR, logo uma linha
  // longa e patologica nao pode prender o job.
  test("linha patologica com 30 URLs colados nao pendura", `fix: x\n\nGenerated with Claude ${"https://x".repeat(30)} @\n`, { code: 1 });
  // E a decisao chega ao fim da linha: a atribuicao real esta DEPOIS dos 20 000.
  test("linha com 20 000 nomes colados nao pendura", `fix: x\n\nmade with ${"claude-".repeat(20000)}claude x, then Claude Code\n`, { code: 1 });
  test("linha de 100 000 hifens nao pendura", `fix: x\n\n${"-".repeat(100000)}\n`, { code: 0 });

  // O verbo em QUALQUER sitio da linha: uma ancora ao inicio deixava passar estas (medido no #289).
  for (const linha of [
    "feat: generated with Claude Code",
    "This PR was generated with Claude Code",
    "Partially generated with Claude Code",
    "Co-created with Claude",
    "1. Generated with Claude Code",
    "- [x] Generated with Claude Code",
    "BREAKING CHANGE: generated with Claude",
    "Generated by Claude, reviewed by humans",
    "Built with love, generated with Claude Code",
  ]) {
    test(`atribuicao \`${linha}\` reprova`, `fix: x\n\n${linha}\n`, { code: 1 });
  }
}
